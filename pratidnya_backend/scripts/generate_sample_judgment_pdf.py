import fitz  # PyMuPDF
from pathlib import Path

def create_sample_judgment_pdf(output_path: str):
    doc = fitz.open()
    page = doc.new_page()

    judgment_text = """
न्यायालय अपर सत्र न्यायाधीश, न्यायालय संख्या 4, लखनऊ
सत्र परीक्षण संख्या: 342/2021 (मु.अ.सं. 124/2020)
थाना: कोतवाली नगर, जिला: लखनऊ
राज्य बनाम राजू उर्फ राजेश
दिनांक: 2024-03-15
पीठासीन अधिकारी: श्री सुरेश चन्द्र, अपर सत्र न्यायाधीश

निर्णय एवं आदेश

1. अभियोजन कथानक संक्षेप में यह है कि वादी मुकदमा राम स्वरूप (PW-1) ने थाना कोतवाली नगर पर लिखित तहरीर दी कि दिनांक 12-08-2020 को अभियुक्त राजू ने जान से मारने की नीयत से लाठी-डंडों से प्रहार कर गंभीर चोटें पहुंचाई।
2. विवेचनाधिकारी ने आरोप-पत्र अंतर्गत धारा 307, 323 भा.दं.वि. न्यायालय में प्रेषित किया।
3. अभियोजन की ओर से चश्मदीद साक्षी PW-1 राम स्वरूप एवं चिकित्सकीय परीक्षण करने वाले डॉ. ए.के. वर्मा (PW-2) की गवाही कराई गई।
4. PW-1 ने बयान दिया कि अभियुक्त ने सीधे सिर पर जानलेवा वार किया, जबकि PW-2 डॉक्टर ने स्वीकार किया कि चोट साधारण प्रकृति की थी और किसी धारदार हथियार का प्रयोग नहीं हुआ था। यह चश्मदीद गवाही और मेडिकल साक्ष्य के मध्य गंभीर अंतर्विरोध है।
5. अभियुक्त का धारा 313 दं.प्र.सं. का बयान दर्ज किया गया जिसमें बरामदगी व FSL रिपोर्ट के तथ्य अभियुक्त के समक्ष स्पष्टीकरण हेतु नहीं रखे गए।
6. पत्रावली पर उपलब्ध मौखिक एवं दस्तावेजी साक्ष्यों के विश्लेषणोपरांत अभियोजन पक्ष संदेह से परे मामला साबित करने में सफल रहा है।

दंडादेश:
अभियुक्त राजू उर्फ राजेश को धारा 307 भा.दं.वि. के अपराध हेतु 7 वर्ष के कठोर कारावास एवं ₹5,000 अर्थदंड तथा धारा 323 भा.दं.वि. में 1 वर्ष के कठोर कारावास से दंडित किया जाता है। अर्थदंड न अदा करने पर 3 माह का अतिरिक्त कारावास भुगतना होगा। सभी सजाएं साथ-साथ चलेंगी।
    """.strip()

    # Use insert_text with a bounding rectangle
    rect = fitz.Rect(50, 50, 550, 750)
    page.insert_textbox(rect, judgment_text, fontsize=11)

    doc.save(output_path)
    doc.close()
    print(f"Sample judgment PDF created at: {output_path}")

if __name__ == "__main__":
    pdf_path = Path(__file__).resolve().parent / "sample_trial_judgment.pdf"
    create_sample_judgment_pdf(str(pdf_path))
